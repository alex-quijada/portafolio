-- Schema de referencia (Portfolio OS)
-- Espejo del esquema real usado por la app. Ejecuta en Supabase > SQL Editor
-- si necesitas recrear las tablas en un proyecto nuevo.

-- Tabla de proyectos
create table if not exists public.projects (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text not null default '',
  repoUrl     text,
  liveUrl     text,
  createdAt   timestamptz not null default now(),
  image       text,
  featured    boolean not null default false
);

alter table public.projects enable row level security;

create policy "Public read projects"
  on public.projects
  for select
  using (true);

-- Tabla de categorias
create table if not exists public.categories (
  id    bigint generated by default as identity primary key,
  slug  text not null unique,
  label text not null
);

alter table public.categories enable row level security;

create policy "Public read categories"
  on public.categories
  for select
  using (true);

-- Tabla puente proyectos <-> categorias
create table if not exists public.project_categories (
  project_id  bigint not null references public.projects (id) on delete cascade,
  category_id bigint not null references public.categories (id) on delete cascade,
  primary key (project_id, category_id)
);

alter table public.project_categories enable row level security;

create policy "Public read project_categories"
  on public.project_categories
  for select
  using (true);

