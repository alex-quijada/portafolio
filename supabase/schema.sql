-- Canciones (app de Música)
create table if not exists public.tracks (
  id          bigint generated by default as identity primary key,
  title       text not null,
  url         text not null,
  created_at  timestamptz not null default now()
);
alter table public.tracks enable row level security;
create policy "Public read tracks" on public.tracks for select using (true);
create policy "Admin write tracks" on public.tracks for all to authenticated using (true) with check (true);

-- Tecnologías (tags de proyectos)
create table if not exists public.technologies (
  id    bigint generated by default as identity primary key,
  name  text not null,
  slug  text not null unique,
  logo  text
);
alter table public.technologies enable row level security;
create policy "Public read technologies" on public.technologies for select using (true);
create policy "Admin write technologies" on public.technologies for all to authenticated using (true) with check (true);

-- Puente proyectos <-> tecnologías
create table if not exists public.project_technologies (
  project_id    bigint not null references public.projects (id) on delete cascade,
  technology_id bigint not null references public.technologies (id) on delete cascade,
  primary key (project_id, technology_id)
);
alter table public.project_technologies enable row level security;
create policy "Public read project_technologies" on public.project_technologies for select using (true);
create policy "Admin write project_technologies" on public.project_technologies for all to authenticated using (true) with check (true);

-- Textos editables (chat / portfolio)
create table if not exists public.content_settings (
  key   text primary key,
  value text not null default ''
);
alter table public.content_settings enable row level security;
create policy "Public read content_settings" on public.content_settings for select using (true);
create policy "Admin write content_settings" on public.content_settings for all to authenticated using (true) with check (true);

